#!/usr/bin/env bash
# Run from the directory containing the original DVD ISO and preseed.cfg.
set -euo pipefail
umask 077

usage() {
    cat <<'EOF'
Usage: build-preseed-dvd.sh TECH_PASSWORD DRIVE LVM_PASSPHRASE HOSTNAME NAME [DVD_ISO] [TEMPLATE]

Defaults: DVD_ISO=debian-13.7.0-amd64-DVD-1.iso, TEMPLATE=preseed.cfg
Outputs: preseed-NAME.cfg and ORIGINAL-DVD-NAME.iso in the current directory.
Example: ./build-preseed-dvd.sh 'abc12345' /dev/sda 'a long disk passphrase' ax2 ax2

Preserves other template settings, including keyboard, packages and poweroff.
Builds an image only; does not write a USB or modify the specified drive.
When booted, the image automatically repartitions that drive after 5 seconds.
Passwords are stored in the output files and may appear in shell history/process arguments.
Existing outputs are never overwritten. Run without sudo.
EOF
}
if [[ ${1:-} == --help || ${1:-} == -h ]]; then usage; exit 0; fi
if (( $# < 5 || $# > 7 )); then usage >&2; exit 2; fi
for tool in python3 xorriso mktemp; do
    command -v "$tool" >/dev/null || { echo "Missing tool: $tool" >&2; exit 1; }
done

export BUILD_TECH_PASSWORD=$1 BUILD_TARGET_DRIVE=$2 BUILD_LVM_PASSWORD=$3
export BUILD_HOSTNAME=$4 BUILD_IMAGE_NAME=$5
source_iso=${6:-debian-13.7.0-amd64-DVD-1.iso}
template=${7:-preseed.cfg}
[[ -r "$source_iso" && -r "$template" ]] || { echo 'Cannot read ISO or template.' >&2; exit 1; }
source_name=$(basename -- "$source_iso")
[[ "$source_name" == *-DVD-1.iso ]] || { echo 'Input filename must end in -DVD-1.iso.' >&2; exit 1; }
python3 - <<'PY'
import os, re, sys
def fail(message):
    sys.exit(message)
for key in ('BUILD_TECH_PASSWORD', 'BUILD_LVM_PASSWORD'):
    value = os.environ[key]
    if not value or value != value.strip() or any(c in value for c in '\r\n\x00'):
        fail('Passwords must be nonempty single lines without leading/trailing whitespace.')
if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,63}', os.environ['BUILD_IMAGE_NAME']):
    fail('Image name must be 1-64 letters, digits, underscores or hyphens; start with a letter/digit.')
if not re.fullmatch(r'[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?', os.environ['BUILD_HOSTNAME']):
    fail('Hostname must be a single valid DNS label (1-63 letters, digits or hyphens).')
if not re.fullmatch(r'/dev/(?:sd[a-z]+|vd[a-z]+|xvd[a-z]+|nvme\d+n\d+|mmcblk\d+)', os.environ['BUILD_TARGET_DRIVE']):
    fail('Use a whole disk, e.g. /dev/sda or /dev/nvme0n1, not a partition.')
PY

output_cfg="preseed-${BUILD_IMAGE_NAME}.cfg"
output_iso="${source_name%-1.iso}-${BUILD_IMAGE_NAME}.iso"
[[ ! -e "$output_cfg" && ! -L "$output_cfg" && ! -e "$output_iso" && ! -L "$output_iso" ]] || {
    echo 'An output already exists. Choose a new name or remove the old outputs.' >&2; exit 1;
}
work_dir=$(mktemp -d "$PWD/.preseed-build.XXXXXXXX")
trap 'rm -rf -- "$work_dir"' EXIT

python3 - "$template" "$work_dir/preseed.cfg" <<'PY'
import os, re, sys
from pathlib import Path
settings = {
    'passwd/user-fullname': ('string', 'Tech'),
    'passwd/username': ('string', 'tech'),
    'passwd/root-login': ('boolean', 'false'),
    'passwd/make-user': ('boolean', 'true'),
    'passwd/user-password': ('password', os.environ['BUILD_TECH_PASSWORD']),
    'passwd/user-password-again': ('password', os.environ['BUILD_TECH_PASSWORD']),
    'partman-auto/disk': ('string', os.environ['BUILD_TARGET_DRIVE']),
    'grub-installer/bootdev': ('string', os.environ['BUILD_TARGET_DRIVE']),
    'partman-auto/method': ('string', 'crypto'),
    'partman-crypto/passphrase': ('password', os.environ['BUILD_LVM_PASSWORD']),
    'partman-crypto/passphrase-again': ('password', os.environ['BUILD_LVM_PASSWORD']),
    'netcfg/get_hostname': ('string', os.environ['BUILD_HOSTNAME']),
    'netcfg/hostname': ('string', os.environ['BUILD_HOSTNAME']),
}
# Remove incompatible hash/root-password settings and all replaced keys.
remove = set(settings) | {
    'passwd/user-password-crypted', 'passwd/root-password',
    'passwd/root-password-again', 'passwd/root-password-crypted',
}
logical = []
pending = ''
for line in Path(sys.argv[1]).read_text().splitlines():
    if not pending and line.lstrip().startswith('#'):
        logical.append(line)
        continue
    pending += line
    if pending.endswith('\\'):
        pending = pending[:-1] + ' '
        continue
    logical.append(pending)
    pending = ''
if pending:
    sys.exit('Template has an unfinished continuation line.')
kept = []
for line in logical:
    match = re.match(r'^\s*d-i\s+(\S+)\s+', line)
    if not match or match[1] not in remove:
        kept.append(line)
kept += ['', '# Per-image settings generated by build-preseed-dvd.sh']
kept += [f'd-i {key} {kind} {value}' for key, (kind, value) in settings.items()]
Path(sys.argv[2]).write_text('\n'.join(kept) + '\n')
PY
unset BUILD_TECH_PASSWORD BUILD_LVM_PASSWORD BUILD_TARGET_DRIVE BUILD_HOSTNAME BUILD_IMAGE_NAME

# Extract only the small files we change; retain the original package tree in the ISO.
xorriso -abort_on FAILURE -osirrox on -indev "$source_iso" \
    -extract /boot/grub/grub.cfg "$work_dir/grub.cfg" \
    -extract /isolinux/isolinux.cfg "$work_dir/isolinux.cfg" \
    -extract /md5sum.txt "$work_dir/md5sum.txt"
chmod u+w "$work_dir/grub.cfg" "$work_dir/isolinux.cfg" "$work_dir/md5sum.txt"

cat >> "$work_dir/grub.cfg" <<'EOF'

menuentry "Automatic Debian baseline installation" --id baseline-auto {
    linux /install.amd/vmlinuz auto=true priority=critical interface=auto netcfg/dhcp_timeout=60 file=/cdrom/preseed.cfg --- quiet
    initrd /install.amd/initrd.gz
}
set default=baseline-auto
set timeout_style=menu
set timeout=5
EOF
cat > "$work_dir/isolinux.cfg" <<'EOF'
DEFAULT baseline-auto
PROMPT 0
TIMEOUT 50
LABEL baseline-auto
    KERNEL /install.amd/vmlinuz
    APPEND initrd=/install.amd/initrd.gz auto=true priority=critical interface=auto netcfg/dhcp_timeout=60 file=/cdrom/preseed.cfg --- quiet
EOF

python3 - "$work_dir" <<'PY'
import hashlib, sys
from pathlib import Path
root = Path(sys.argv[1])
changed = {'./boot/grub/grub.cfg': 'grub.cfg',
           './isolinux/isolinux.cfg': 'isolinux.cfg', './preseed.cfg': 'preseed.cfg'}
manifest = root / 'md5sum.txt'
kept = []
for line in manifest.read_text().splitlines():
    fields = line.split(maxsplit=1)
    if len(fields) == 2:
        name = fields[1].lstrip('*')
        name = './' + name.removeprefix('./')
        if name in changed:
            continue
    kept.append(line)
for name, local in sorted(changed.items()):
    digest = hashlib.md5((root / local).read_bytes()).hexdigest()
    kept.append(f'{digest}  {name}')
manifest.write_text('\n'.join(kept) + '\n')
PY

xorriso -abort_on FAILURE \
    -indev "$source_iso" -outdev "$work_dir/result.iso" \
    -map "$work_dir/preseed.cfg" /preseed.cfg \
    -map "$work_dir/grub.cfg" /boot/grub/grub.cfg \
    -map "$work_dir/isolinux.cfg" /isolinux/isolinux.cfg \
    -map "$work_dir/md5sum.txt" /md5sum.txt \
    -boot_image any replay

# Verify the embedded configuration before publishing either output.
xorriso -abort_on FAILURE -osirrox on -indev "$work_dir/result.iso" \
    -extract /preseed.cfg "$work_dir/verified.cfg"
cmp -- "$work_dir/preseed.cfg" "$work_dir/verified.cfg"
chmod 600 "$work_dir/result.iso" "$work_dir/preseed.cfg"
# Hard links publish without overwriting an existing pathname; temp dir is on same filesystem.
ln -- "$work_dir/result.iso" "$output_iso"
if ! ln -- "$work_dir/preseed.cfg" "$output_cfg"; then
    rm -f -- "$output_iso"
    exit 1
fi
printf 'Created: %s\nCreated: %s\n' "$output_cfg" "$output_iso"
